import streamlit as st

st.title("Вход и регистрация")

# ВРЕМЕННЫЙ ВХОД: нужен, чтобы проверять остальные экраны, пока нет настоящего.
# В задаче «Экран входа и регистрации» весь этот блок заменяется входом по почте и паролю.
st.info("Настоящий вход по почте появится позже. Пока введи любой псевдоним, например «Тестовый Енот #111».")
test_pseudonym = st.text_input("Псевдоним для проверки")
if st.button("Войти для проверки") and test_pseudonym:
    st.session_state["pseudonym"] = test_pseudonym
    st.rerun()

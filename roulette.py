"""
Модуль бизнес-логики сервиса PeerCheck.
Отвечает за правила назначения работ и проверки доступа.
"""


def get_random_lab_for_review(current_user_token: str) -> int:
    """
    Выбирает случайную работу из очереди для проверки.

    Правила:
    1. Работа не должна принадлежать самому current_user_token.
    2. Работа не должна быть уже проверена этим пользователем.

    current_user_token: Анонимный идентификатор текущего студента.
    ID лабораторной работы для проверки (int).
    """
    # Заглушка для Спринта 1
    print(f"[Logic] Запрос работы для пользователя: {current_user_token}")
    return 101  # Фейковый ID работы


def can_view_own_reviews(current_user_token: str) -> bool:
    """
    Проверяет, имеет ли право студент смотреть отзывы на свою работу.

    Правило:
    Доступ разрешен ТОЛЬКО если студент уже отправил хотя бы 1 качественную
    рецензию на чужую работу.

    current_user_token: Анонимный идентификатор студента.
    True, если доступ открыт, иначе False.
    """
    # Заглушка: пока доступ закрыт
    return False


def validate_review_comment(comment_text: str) -> bool:
    """
    Защита от 'протыкивания наугад': проверяет, что комментарий к отзыву
    достаточно информативен (не менее 50 символов).

    comment_text: Текст комментария рецензента.
    True, если отзыв валиден, иначе False.
    """
    clean_text = comment_text.strip()
    return len(clean_text) >= 50


